#!/usr/bin/env bash
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
command -v clang-format >/dev/null || { echo "clang-format is required" >&2; exit 2; }

files=(
  "$root/src/agv_map_3d/src/map_3d_server.cpp"
  "$root/src/agv_map_3d/src/assets.cpp"
  "$root/src/agv_map_3d/include/agv_map_3d/assets.hpp"
)
clang-format --dry-run --Werror "${files[@]}"

if command -v clang-tidy >/dev/null; then
  echo "clang-tidy is available; run it with the compile_commands.json generated by colcon."
else
  echo "clang-tidy not installed; skipped (optional developer tool)."
fi
